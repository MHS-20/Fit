def cmd_status_branch(repo):
    branch = branch_get_active(repo)
    if branch:
        print(f"On branch {branch}.")
    else:
        print(f"HEAD detached at {object_find(repo, 'HEAD')}")


def cmd_status_head_index(repo, index):
    print("Changes to be committed:")

    branch = branch_get_active(repo)
    ref = os.path.join("refs/heads", branch) if branch else "HEAD"
    head_sha = ref_resolve(repo, ref)

    if not head_sha:
        # No commits yet — everything in the index is "new"
        for entry in index.entries:
            print("  added:   ", entry.name)
        return

    head = tree_to_dict(repo, "HEAD")
    for entry in index.entries:
        if entry.name in head:
            if head[entry.name] != entry.sha:
                print("  modified:", entry.name)
            del head[entry.name]
        else:
            print("  added:   ", entry.name)
    for entry in head.keys():
        print("  deleted: ", entry)


def cmd_status_index_worktree(repo, index):
    print("Changes not staged for commit:")
    ignore = fitignore_read(repo)
    gitdir_prefix = repo.fitdir + os.path.sep
    all_files = list()

    for root, _, files in os.walk(repo.worktree, True):
        if root == repo.fitdir or root.startswith(gitdir_prefix):
            continue
        for f in files:
            full_path = os.path.join(root, f)
            rel_path = os.path.relpath(full_path, repo.worktree)
            all_files.append(rel_path)

    for entry in index.entries:
        full_path = os.path.join(repo.worktree, entry.name)
        if not os.path.exists(full_path):
            print("  deleted: ", entry.name)
        else:
            stat = os.stat(full_path)
            ctime_ns = entry.ctime[0] * 10**9 + entry.ctime[1]
            mtime_ns = entry.mtime[0] * 10**9 + entry.mtime[1]
            if (stat.st_ctime_ns != ctime_ns) or (stat.st_mtime_ns != mtime_ns):
                with open(full_path, "rb") as fd:
                    new_sha = object_hash(fd, b"blob", None)
                    if entry.sha != new_sha:
                        print("  modified:", entry.name)
        if entry.name in all_files:
            all_files.remove(entry.name)

    print()
    print("Untracked files:")
    for f in all_files:
        if not check_ignore(ignore, f):
            print(" ", f)


