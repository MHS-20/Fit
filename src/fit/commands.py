def cmd_init(args):
    repo_create(args.path)


def cmd_cat_file(args):
    repo = repo_find()
    cat_file(repo, args.object, fmt=args.type.encode())


def cmd_hash_object(args):
    if args.write:
        repo = repo_find()
    else:
        repo = None
    with open(args.path, "rb") as fd:
        sha = object_hash(fd, args.type.encode(), repo)
        print(sha)


def cmd_log(args):
    repo = repo_find()
    branch = branch_get_active(repo)
    ref = os.path.join("refs/heads", branch) if branch else "HEAD"
    sha = ref_resolve(repo, ref)
    if not sha:
        raise Exception("No commits yet.")
    log(repo, sha, set())


def cmd_ls_tree(args):
    repo = repo_find()
    ls_tree(repo, args.tree, args.recursive)


def cmd_checkout(args):
    repo = repo_find()
    obj = object_read(repo, object_find(repo, args.commit))
    if obj.fmt == b"commit":
        obj = object_read(repo, obj.kvlm[b"tree"].decode("ascii"))
    if os.path.exists(args.path):
        if not os.path.isdir(args.path):
            raise Exception(f"Not a directory {args.path}!")
        if os.listdir(args.path):
            raise Exception(f"Not empty {args.path}!")
    else:
        os.makedirs(args.path)
    tree_checkout(repo, obj, os.path.realpath(args.path))


def cmd_show_ref(args):
    repo = repo_find()
    refs = ref_list(repo)
    show_ref(repo, refs, prefix="refs")


def cmd_tag(args):
    repo = repo_find()
    if args.name:
        tag_create(
            repo, args.name, args.object, create_tag_object=args.create_tag_object
        )
    else:
        refs = ref_list(repo)
        show_ref(repo, refs["tags"], with_hash=False)


def cmd_rev_parse(args):
    fmt = args.type.encode() if args.type else None
    repo = repo_find()
    print(object_find(repo, args.name, fmt, follow=True))


def cmd_ls_files(args):
    repo = repo_find()
    index = index_read(repo)
    if args.verbose:
        print(
            f"Index file format v{index.version}, containing {len(index.entries)} entries."
        )

    for e in index.entries:
        print(e.name)
        if args.verbose:
            entry_type = {
                0b1000: "regular file",
                0b1010: "symlink",
                0b1110: "git link",
            }[e.mode_type]
            print(f"  {entry_type} with perms: {e.mode_perms:o}")
            print(f"  on blob: {e.sha}")
            print(
                f"  created: {datetime.fromtimestamp(e.ctime[0])}.{e.ctime[1]}, "
                f"modified: {datetime.fromtimestamp(e.mtime[0])}.{e.mtime[1]}"
            )
            print(f"  device: {e.dev}, inode: {e.ino}")
            try:
                print(
                    f"  user: {pwd.getpwuid(e.uid).pw_name} ({e.uid})  "
                    f"group: {grp.getgrgid(e.gid).gr_name} ({e.gid})"
                )
            except NameError:
                print(f"  user: {e.uid}  group: {e.gid}")
            print(f"  flags: stage={e.flag_stage} assume_valid={e.flag_assume_valid}")


def cmd_check_ignore(args):
    repo = repo_find()
    rules = fitignore_read(repo)
    for path in args.path:
        if check_ignore(rules, path):
            print(path)


def cmd_status(_):
    repo = repo_find()
    index = index_read(repo)
    cmd_status_branch(repo)
    cmd_status_head_index(repo, index)
    print()
    cmd_status_index_worktree(repo, index)


def cmd_rm(args):
    repo = repo_find()
    rm(repo, args.path)


def cmd_add(args):
    repo = repo_find()
    add(repo, args.path)


def cmd_commit(args):
    repo = repo_find()
    index = index_read(repo)
    tree = tree_from_index(repo, index)

    author = fitconfig_user_get(fitconfig_read())
    if not author:
        raise Exception(
            "User not configured. Add to ~/.fitconfig:\n"
            "[user]\n"
            "    name = Your Name\n"
            "    email = you@example.com"
        )

    branch = branch_get_active(repo)
    ref = os.path.join("refs/heads", branch) if branch else "HEAD"
    parent = ref_resolve(repo, ref)

    commit = commit_create(
        repo,
        tree,
        parent,
        author,
        datetime.now(),
        args.message,
    )

    active_branch = branch_get_active(repo)
    if active_branch:
        with open(
            repo_file(repo, os.path.join("refs/heads", active_branch)), "w"
        ) as fd:
            fd.write(commit + "\n")
    else:
        with open(repo_file(repo, "HEAD"), "w") as fd:
            fd.write("\n")


def cmd_push(args):
    import getpass

    repo = repo_find()

    username = args.username
    password = args.password

    if not username:
        username = input("Username: ")
    if not password:
        password = getpass.getpass("Password / token: ")

    push(repo, args.remote, username, password)
